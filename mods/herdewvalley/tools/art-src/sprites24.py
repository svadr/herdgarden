def build(outdir):
    os.makedirs(outdir, exist_ok=True)
    out = {}
    for name, (art, pal) in {**{'v-' + k: v for k, v in V.items()}, **{'h-' + k: v for k, v in H.items()}}.items():
        rows = art.strip('\n').split('\n')
        bad = [(i, len(r)) for i, r in enumerate(rows) if len(r) != 24]
        assert len(rows) == 24 and not bad, (name, len(rows), bad)
        sp = sprite(art, pal)
        sp.png(os.path.join(outdir, name + '.png'))
        out[name] = sp
    return out


if __name__ == '__main__':
    here = os.path.dirname(__file__)
    sp = build(os.path.join(here, 'art'))
    names = list(sp)
    for label, bg in (('light', hexc('#fbf6ee')), ('dark', hexc('#1a1612'))):
        big = C(len(names) * 27 + 3, 30)
        for i, n in enumerate(names):
            big.blit(sp[n], 3 + i * 27, 3)
        big.png(os.path.join(here, f'sheet24-{label}.png'), scale=7, bg=bg)
    print(names)
